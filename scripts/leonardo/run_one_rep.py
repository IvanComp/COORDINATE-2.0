#!/usr/bin/env python3
"""Run a single repetition of one RQ campaign inside an isolated sandbox.

Each SLURM array task owns one sandbox (see prepare_campaign.sh), so the ten
repetitions never write to the same runs.csv. The runner is imported from the
sandbox copy of "Paper Results", and its campaign builder is wrapped so that
only repetition ``--rep`` is scheduled. Seeds are generated by the original
runner (base_seed + condition_idx * 1000 + rep), so repetition k on LEONARDO
uses exactly the same seed as repetition k of the original campaign and all
mechanisms in a repetition share the seed (paired design).

Usage (from inside a sandbox):
    python run_one_rep.py --sandbox <dir> --rq RQ1 --rep 3 -- --workers 32 --machine-label leonardo
Everything after "--" is forwarded to the RQ runner unchanged.
"""

from __future__ import annotations

import argparse
import importlib
import sys
from pathlib import Path

RUNNERS = {
    "RQ1": ("run_rq1_experiments", "campaign_grid", True),
    "RQ2": ("run_rq2_experiments", "campaign", True),
    "RQ3": ("run_rq3_experiments", "campaign", True),
    # RQ4 applies --limit itself after sharding, so only the row builder is wrapped.
    "RQ4": ("run_rq4_experiments", "build_campaign_rows", False),
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sandbox", required=True, type=Path, help="Sandbox project root for this repetition.")
    parser.add_argument("--rq", required=True, choices=sorted(RUNNERS))
    parser.add_argument("--rep", required=True, type=int, help="1-based repetition index to run.")
    own, forwarded = parser.parse_known_args()
    if forwarded and forwarded[0] == "--":
        forwarded = forwarded[1:]
    if own.rep < 1:
        raise SystemExit("--rep must be >= 1")

    paper_dir = (own.sandbox / "Paper Results").absolute()
    if not (paper_dir / f"{RUNNERS[own.rq][0]}.py").exists():
        raise SystemExit(f"Runner not found in sandbox: {paper_dir}")

    # Make the sandbox the project root for the runner and for any worker
    # process (spawned workers inherit sys.path from the parent).
    sys.path.insert(0, str(own.sandbox.absolute()))
    sys.path.insert(0, str(paper_dir))

    module_name, builder_name, handles_limit = RUNNERS[own.rq]
    module = importlib.import_module(module_name)
    original_builder = getattr(module, builder_name)
    rep = own.rep

    def only_this_rep(args):
        saved_limit = getattr(args, "limit", None)
        if handles_limit:
            args.limit = None
        try:
            rows = [row for row in original_builder(args) if int(row["rep"]) == rep]
        finally:
            args.limit = saved_limit
        if handles_limit and saved_limit:
            rows = rows[:saved_limit]
        return rows

    setattr(module, builder_name, only_this_rep)

    # The runner builds repetitions 1..N, so N must be at least the target rep.
    # Any --repetitions passed by the caller is replaced.
    cleaned = []
    skip = False
    for token in forwarded:
        if skip:
            skip = False
            continue
        if token == "--repetitions":
            skip = True
            continue
        if token.startswith("--repetitions="):
            continue
        cleaned.append(token)
    sys.argv = [str(paper_dir / f"{module_name}.py"), "--repetitions", str(rep), *cleaned]
    print(f"[run_one_rep] {own.rq} rep={rep} sandbox={own.sandbox} argv={sys.argv[1:]}", flush=True)
    module.run_campaign(module.parse_args())


if __name__ == "__main__":
    main()
