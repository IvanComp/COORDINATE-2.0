"""
Latency Monitoring Visualization Script

This script reads the overhead CSV files generated by dynamic adaptation experiments
and creates plots showing the evolution of monitored latency over simulation time.
"""

import csv
import matplotlib.pyplot as plt
from pathlib import Path
import numpy as np

RESULTS_DIR = Path("batch_results")

def read_overhead_data(overhead_csv_path):
    """
    Read overhead CSV and extract latency data.
    
    Returns:
        tuple: (sim_times, latencies, switches)
    """
    sim_times = []
    latencies = []
    switches = []
    
    try:
        with open(overhead_csv_path, 'r') as f:
            reader = csv.DictReader(f)
            for row in reader:
                sim_times.append(float(row['sim_time']))
                lat = row['latency']
                latencies.append(float(lat) if lat and lat != 'None' else None)
                switches.append(row['switched'] == 'True')
        return sim_times, latencies, switches
    except Exception as e:
        print(f"Error reading {overhead_csv_path}: {e}")
        return [], [], []

def plot_latency_evolution(exp_dirs, output_path="latency_evolution.png"):
    """
    Create a multi-panel plot showing latency evolution for all experiments.
    
    Args:
        exp_dirs: List of experiment directories
        output_path: Path to save the plot
    """
    n_experiments = len(exp_dirs)
    
    if n_experiments == 0:
        print("No experiments found!")
        return
    
    # Create subplots
    fig, axes = plt.subplots(n_experiments, 1, figsize=(12, 4 * n_experiments))
    if n_experiments == 1:
        axes = [axes]
    
    for idx, exp_dir in enumerate(exp_dirs):
        ax = axes[idx]
        
        # Find overhead CSV
        overhead_files = list(exp_dir.glob("*_overhead.csv"))
        if not overhead_files:
            ax.text(0.5, 0.5, f"No overhead data for {exp_dir.name}", 
                   ha='center', va='center', transform=ax.transAxes)
            continue
        
        overhead_csv = overhead_files[0]
        sim_times, latencies, switches = read_overhead_data(overhead_csv)
        
        if not sim_times:
            ax.text(0.5, 0.5, f"Empty data for {exp_dir.name}", 
                   ha='center', va='center', transform=ax.transAxes)
            continue
        
        # Convert to hours for better readability
        sim_times_hours = [t / 3600 for t in sim_times]
        
        # Plot latency
        valid_indices = [i for i, lat in enumerate(latencies) if lat is not None]
        valid_times = [sim_times_hours[i] for i in valid_indices]
        valid_latencies = [latencies[i] for i in valid_indices]
        
        ax.plot(valid_times, valid_latencies, 'b-', linewidth=1, alpha=0.7, label='Monitored Latency')
        
        # Mark switches
        switch_times = [sim_times_hours[i] for i, sw in enumerate(switches) if sw]
        switch_latencies = [latencies[i] for i, sw in enumerate(switches) if sw and latencies[i] is not None]
        
        if switch_times:
            ax.scatter(switch_times, switch_latencies, c='red', s=50, 
                      marker='x', linewidths=2, label=f'Switches ({len(switch_times)})', zorder=5)
        
        # Add threshold lines
        ax.axhline(y=10, color='green', linestyle='--', linewidth=1.5, alpha=0.7, label='Green Threshold (10s)')
        ax.axhline(y=40, color='orange', linestyle='--', linewidth=1.5, alpha=0.7, label='Yellow Threshold (40s)')
        
        # Styling
        ax.set_xlabel('Simulation Time (hours)', fontsize=10)
        ax.set_ylabel('Latency (seconds)', fontsize=10)
        ax.set_title(f'{exp_dir.name}', fontsize=11, fontweight='bold')
        ax.grid(True, alpha=0.3)
        ax.legend(loc='upper right', fontsize=8)
        
        # Add statistics
        if valid_latencies:
            mean_lat = np.mean(valid_latencies)
            max_lat = np.max(valid_latencies)
            min_lat = np.min(valid_latencies)
            stats_text = f'Mean: {mean_lat:.1f}s | Min: {min_lat:.1f}s | Max: {max_lat:.1f}s'
            ax.text(0.02, 0.98, stats_text, transform=ax.transAxes, 
                   fontsize=8, verticalalignment='top',
                   bbox=dict(boxstyle='round', facecolor='wheat', alpha=0.5))
    
    plt.tight_layout()
    plt.savefig(output_path, dpi=150, bbox_inches='tight')
    print(f"\n✓ Plot saved to: {output_path}")
    plt.close()

def main():
    """Main function to process all experiments and create plots."""
    
    if not RESULTS_DIR.exists():
        print(f"Results directory not found: {RESULTS_DIR}")
        return
    
    # Find all experiment directories
    exp_dirs = sorted([d for d in RESULTS_DIR.iterdir() if d.is_dir() and d.name.startswith('exp_')])
    
    if not exp_dirs:
        print("No experiment directories found!")
        return
    
    print(f"Found {len(exp_dirs)} experiments")
    print("=" * 70)
    
    # Create plot
    plot_latency_evolution(exp_dirs, output_path="latency_evolution.png")
    
    # Also create individual plots for each experiment
    for exp_dir in exp_dirs:
        plot_latency_evolution([exp_dir], output_path=f"{exp_dir.name}_latency.png")
    
    print("=" * 70)
    print("✓ All plots generated successfully!")

if __name__ == "__main__":
    main()
